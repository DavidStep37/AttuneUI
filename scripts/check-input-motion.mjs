import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage();
const target = '.pg-card-slot:nth-child(2) .at-input-box';
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
await mkdir('.backup/input-review', { recursive: true });
try {
  await page.setViewport({ width: 1440, height: 1050, deviceScaleFactor: 2 });
  await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'no-preference' }, { name: 'prefers-color-scheme', value: 'light' }]);
  await page.goto(process.env.ATTUNE_URL ?? 'http://localhost:5188', { waitUntil: 'networkidle0' });
  // Sample each geometric phase at a slower supported setting. The default
  // duration is exercised separately by check-input-panels.mjs.
  await page.evaluate(() => {
    const state = JSON.parse(localStorage.getItem('attune-playground-v1'));
    state.overrides.input = { ...state.overrides.input, drawDuration: 900 };
    localStorage.setItem('attune-playground-v1', JSON.stringify(state));
  });
  await page.reload({ waitUntil: 'networkidle0' });
  const stage = await page.$('.pg-card-slot:nth-child(2)');
  const inspect = () => page.$eval(target, el => {
    const frame = el.querySelector('.at-input-frame'), paths = [...el.querySelectorAll('.at-input-outline path')];
    return { progress: +getComputedStyle(frame).getPropertyValue('--at-input-draw'), grow: +getComputedStyle(frame).getPropertyValue('--at-input-progress'), length: paths.reduce((sum, p) => sum + p.getTotalLength() * (1 - parseFloat(getComputedStyle(p).strokeDashoffset)), 0), surface: +getComputedStyle(el.querySelector('.at-input-surface')).opacity };
  });
  const spacing = () => page.$eval(target, el => {
    const root = el.closest('.at-input').getBoundingClientRect();
    const unit = el.closest('.at-input').querySelector('.at-input-unit').getBoundingClientRect();
    const box = el.getBoundingClientRect(), frame = el.querySelector('.at-input-frame').getBoundingClientRect();
    return { right: root.right - unit.right, gap: unit.left - frame.right, centre: box.x + box.width / 2, rootRight: root.right };
  });
  const restingSpacing = await spacing();
  assert(Math.abs(restingSpacing.right - 4) < 0.1, 'Resting unit reserves 4px on the right');
  assert(Math.abs(restingSpacing.gap - 4) < 0.1, 'Resting number box and unit have a 4px gap');
  assert(Math.abs((await inspect()).length - 20) < 0.1, 'Resting underline is 20px long');
  assert.equal((await inspect()).surface, 0);
  await stage.screenshot({ path: '.backup/input-review/underline-default.png' });
  const startTrace = () => page.$eval(target, el => {
    window.inputTrace = [];
    const start = performance.now();
    const tick = () => {
      const frame = el.querySelector('.at-input-frame'), paths = [...el.querySelectorAll('.at-input-outline path')];
      const r = frame.getBoundingClientRect();
      const ends = paths.map(path => { const offset = parseFloat(getComputedStyle(path).strokeDashoffset), point = path.getPointAtLength(path.getTotalLength() * (1 - offset)); return [point.x, point.y]; });
      window.inputTrace.push({ t: Math.round(performance.now() - start), progress: +getComputedStyle(frame).getPropertyValue('--at-input-draw'), grow: +getComputedStyle(frame).getPropertyValue('--at-input-progress'), surface: +getComputedStyle(el.querySelector('.at-input-surface')).opacity, w: r.width, h: r.height, ends });
      if (performance.now() - start < window.inputTraceDuration) requestAnimationFrame(tick);
    };
    window.inputTraceDuration = 1350;
    tick();
  });
  await startTrace();
  await page.hover(target);
  await pause(170); await stage.screenshot({ path: '.backup/input-review/underline-drawing.png' });
  await pause(1250);
  const trace = await page.evaluate(() => window.inputTrace);
  await writeFile('.backup/input-review/motion-trace.json', JSON.stringify(trace, null, 2));
  assert(trace.filter(f => f.progress > 0.02 && f.progress < 0.98).length >= 8, 'Outline draws through multiple intermediate frames');
  const bottom = trace.findIndex(f => f.progress > 0.01 && Math.abs(f.ends[0][1] - (f.h - 0.5)) < 0.1);
  const side = trace.findIndex(f => Math.abs(f.ends[0][0] - 0.5) < 0.1 && f.ends[0][1] > 6 && f.ends[0][1] < f.h - 6);
  const top = trace.findIndex(f => f.progress < 0.98 && f.ends[0][0] > 6 && Math.abs(f.ends[0][1] - 0.5) < 0.1);
  assert(bottom >= 0 && side > bottom && top > side, 'Stroke proceeds along bottom, up sides, then across top');
  assert(trace.every(f => Math.abs(f.ends[0][1] - f.ends[1][1]) < 0.1 && Math.abs(f.ends[0][0] + f.ends[1][0] - f.w) < 0.1), 'Both strokes draw symmetrically');
  assert.equal((await inspect()).progress, 1);
  assert.equal((await inspect()).grow, 0, 'Hover draws the small frame without expanding it');
  assert(trace.every(f => f.w === trace[0].w && f.h === trace[0].h), 'Hover traces a stable compact rectangle');
  assert(trace.every(f => f.surface === 0), 'A complete surface never appears over the unfinished hover outline');
  await stage.screenshot({ path: '.backup/input-review/hover-closed.png' });
  await startTrace();
  await page.evaluate(() => { window.inputTraceDuration = 950; });
  await page.click(target);
  assert(await page.$eval('.at-input-field', el => el === document.activeElement), 'Clicking immediately focuses the editor');
  await pause(200); await stage.screenshot({ path: '.backup/input-review/focus-expanding.png' });
  await pause(850);
  const expansion = await page.evaluate(() => window.inputTrace);
  assert(expansion.filter(f => f.grow > 0.02 && f.grow < 0.98).length >= 6, 'Focus visibly interpolates through multiple sizes');
  assert(expansion.every(f => f.progress === 1), 'Focus keeps the completed stroke intact');
  assert(Math.abs(expansion.at(-1).w - trace[0].w - 10) < 0.1 && Math.abs(expansion.at(-1).h - trace[0].h - 8) < 0.1, 'Final focus dimensions are unchanged');
  assert.equal((await inspect()).surface, 1);
  const selection = await page.$eval('.at-input-field', el => {
    const css = getComputedStyle(el, '::selection');
    const fill = getComputedStyle(document.querySelector('.at-slider-fill')).fill;
    return { background: css.backgroundColor, color: css.color, fill };
  });
  assert.equal(selection.background, selection.fill, 'Selected text uses the Slider fill color');
  assert.notEqual(selection.background, selection.color, 'Selected digits remain visible');
  const editingSpacing = await spacing();
  assert(Math.abs(editingSpacing.right) < 0.1, 'Editing unit consumes right padding and aligns with container');
  assert(Math.abs(editingSpacing.gap - 3) < 0.1, 'Editing border leaves a 3px gap before the unit');
  assert(Math.abs(editingSpacing.centre - restingSpacing.centre) < 0.1, 'Digits do not move when the unit moves');
  assert(Math.abs(editingSpacing.rootRight - restingSpacing.rootRight) < 0.1, 'Container right alignment stays fixed');
  await stage.screenshot({ path: '.backup/input-review/underline-closed.png' });
  await page.keyboard.type('420'); await page.keyboard.press('Enter');
  assert.equal(await page.$eval(target, el => el.getAttribute('aria-valuenow')), '420');
  await page.$eval(target, el => el.blur()); await pause(650);
  assert.equal((await inspect()).progress, 1, 'Blur while still hovered retains the compact closed frame');
  assert.equal((await inspect()).grow, 0, 'Blur gently shrinks back to hover size');
  await page.mouse.move(0, 0); await pause(700);
  assert.equal((await inspect()).progress, 0, 'Blur reverses the drawing back to an underline');
  assert(Math.abs((await spacing()).right - 4) < 0.1, 'Blur restores the unit right padding');
  await page.hover('.pg-card-slot:nth-child(2) .at-input-unit'); await pause(200);
  assert.equal((await inspect()).progress, 0, 'Only the number region draws the hover frame');
  await startTrace();
  await page.evaluate(() => { window.inputTraceDuration = 1900; });
  await page.hover(target); await pause(60);
  const partial = (await inspect()).progress;
  assert(partial > 0 && partial < 0.8);
  await page.click(target);
  const resumed = (await inspect()).progress;
  assert(resumed >= partial - 0.03 && resumed < 0.9, 'Early click continues the existing trace without resetting or snapping closed');
  await pause(1800);
  const quickClick = await page.evaluate(() => window.inputTrace);
  assert(quickClick.some(f => f.progress > 0.05 && f.progress < 0.9), 'Quick click retains a visible drawing phase');
  assert(quickClick.every(f => f.progress >= 0.999 || f.grow === 0), 'Expansion waits for the outline to close even on quick click');
  assert(quickClick.every(f => Math.abs(f.surface - f.grow) < 0.035), 'Surface fades across the entire expansion rather than popping in at closure');
  assert(quickClick.filter(f => f.grow > 0.02 && f.grow < 0.98).length >= 6, 'Quick click also preserves a gradual expansion phase');
  await writeFile('.backup/input-review/quick-click-trace.json', JSON.stringify(quickClick, null, 2));
  assert.equal((await inspect()).grow, 1);
  await page.mouse.move(0, 0); await pause(500);
  assert.equal((await inspect()).progress, 1, 'Focused frame remains drawn after pointer leave');
  await page.click('.pg-brand-name'); await pause(700);
  await page.hover(target); await pause(180); await page.mouse.move(0, 0); await pause(700);
  assert.equal((await inspect()).progress, 0, 'Interrupted hover retracts to the original underline');
  await page.click('[aria-label="减弱动效"]'); await page.click(target); await pause(100);
  assert.equal((await inspect()).progress, 1, 'Reduced motion draws the complete editable frame immediately');
  await writeFile('.backup/input-review/motion-trace.json', JSON.stringify(trace, null, 2));
  console.log('PASS Input: hover drawing, gradual focus expansion, stable digits/spacing, selection, editing, blur and reduced motion');
} finally { await browser.close(); }
